// CORDIC. 16 rotations gives the full 16 bits of a BAM16 angle; the gain is folded into the
// comparison rather than the result, since only the ANGLE is wanted.
int32_t atan2_bam16(int32_t y, int32_t x) {
    // atan(2^-i) in BAM16, i = 0..15.
    static const int32_t kAtan[16] = {
        8192, 4836, 2555, 1297, 651, 326, 163, 81, 41, 20, 10, 5, 3, 1, 1, 0,
    };
    if (x == 0 && y == 0) return 0;
    int32_t angle = 0;
    // Fold into the right half-plane first; CORDIC only converges for |angle| <= 90 degrees.
    if (x < 0) {
        x = -x;
        y = -y;
        angle = 32768; // 180 degrees
    }
    // Keep the magnitudes small enough that the 1.647 CORDIC gain cannot overflow.
    while (x > (1 << 24) || y > (1 << 24) || y < -(1 << 24)) {
        x >>= 1;
        y >>= 1;
    }
    for (int i = 0; i < 16; ++i) {
        const int32_t xi = x, yi = y;
        if (y > 0) {
            x = xi + (yi >> i);
            y = yi - (xi >> i);
            angle += kAtan[i];
        } else if (y < 0) {
            x = xi - (yi >> i);
            y = yi + (xi >> i);
            angle -= kAtan[i];
        } else {
            break;
        }
    }
    return angle & 0xFFFF;
}

